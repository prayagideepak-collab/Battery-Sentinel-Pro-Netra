import androidx.compose.ui.unit.sp
import com.example.model.DotState
import com.example.ui.theme.NetraCardBorder
import com.example.ui.theme.NetraCyan

@Composable
fun SentinelCard(
    title: String,
    icon: ImageVector,
    dotState: DotState? = null,
    modifier: Modifier = Modifier,
    accentColor: Color = NetraCyan,
    trailingAction: (@Composable () -> Unit)? = null,
    content: @Composable ColumnScope.() -> Unit
) {
    Box(
        modifier = modifier
            .fillMaxWidth()
            .clip(RoundedCornerShape(16.dp))
            .background(MaterialTheme.colorScheme.surface)
            .border(1.dp, NetraCardBorder.copy(alpha = 0.6f), RoundedCornerShape(16.dp))
            .padding(16.dp)
    ) {
        Column {
            // Header Row
            Row(
                modifier = Modifier.fillMaxWidth(),
                horizontalArrangement = Arrangement.SpaceBetween,
                verticalAlignment = Alignment.CenterVertically
            ) {
                Row(
                    verticalAlignment = Alignment.CenterVertically,
                    modifier = Modifier.weight(1f, fill = false)
                ) {
                    Box(
                        modifier = Modifier
                            .size(32.dp)
                            .clip(RoundedCornerShape(8.dp))
                            .background(accentColor.copy(alpha = 0.15f)),
                        contentAlignment = Alignment.Center
                    ) {
                        Icon(
                            imageVector = icon,
                            contentDescription = title,
                            tint = accentColor,
                            modifier = Modifier.size(18.dp)
                        )
                    }
                    Spacer(modifier = Modifier.width(10.dp))
                    Text(
                        text = title,
                        fontSize = 15.sp,
                        fontWeight = FontWeight.Bold,
                        color = MaterialTheme.colorScheme.onSurface
                    )
                }

                Row(verticalAlignment = Alignment.CenterVertically) {
                    if (dotState != null) {
                        StatusDot(state = dotState, showLabel = false)
                        Spacer(modifier = Modifier.width(8.dp))
                    }
                    trailingAction?.invoke()
                }
            }

            Spacer(modifier = Modifier.height(14.dp))

            // Body Content
            content()
        }
    }
}
